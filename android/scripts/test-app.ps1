[CmdletBinding()]
param(
    [switch]$VerifyOnly,
    [string]$DeviceSerial,
    [string]$AdbPath,
    # Verification fixture root only; contains app/build and share-sdk/build.
    [string]$OutputRoot
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$androidRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
if (!$OutputRoot) { $OutputRoot = $androidRoot }
$OutputRoot = [IO.Path]::GetFullPath($OutputRoot)

function Require-File([string]$Path) {
    if (!(Test-Path -LiteralPath $Path -PathType Leaf)) { throw "Missing deliverable: $Path" }
    if ((Get-Item -LiteralPath $Path).Length -eq 0) { throw "Empty deliverable: $Path" }
}

function Test-StaticContract {
    foreach ($relative in @('gradlew.bat', 'settings.gradle.kts', 'app/build.gradle.kts', 'share-sdk/build.gradle.kts')) {
        Require-File (Join-Path $androidRoot $relative)
    }
    $settings = Get-Content -LiteralPath (Join-Path $androidRoot 'settings.gradle.kts') -Raw
    foreach ($module in @('app', 'share-sdk')) {
        if ($settings -notmatch ('include\(":' + [regex]::Escape($module) + '"\)')) { throw "Missing Gradle module: $module" }
    }
    $app = Get-Content -LiteralPath (Join-Path $androidRoot 'app/build.gradle.kts') -Raw
    $sdk = Get-Content -LiteralPath (Join-Path $androidRoot 'share-sdk/build.gradle.kts') -Raw
    if ($app -notmatch 'libs.plugins.android.application' -or $sdk -notmatch 'com.android.library') { throw 'Missing Android Gradle plugin task contract' }
    foreach ($requirement in @('minSdk\s*=\s*26\b', 'targetSdk\s*=\s*36\b', 'compileSdk\s*=\s*36\b', 'androidx.test.runner.AndroidJUnitRunner')) {
        if ($app -notmatch $requirement) { throw "App Gradle contract mismatch: $requirement" }
    }
    # These tasks are generated by AGP for the included debug variants; normal mode
    # also checks the real task inventory before executing them. VerifyOnly runs no Gradle.
    Write-Output 'Static task contract: :app:assembleDebug/testDebugUnitTest/lintDebug/connectedDebugAndroidTest; :share-sdk:assembleDebug/testDebugUnitTest/connectedDebugAndroidTest'
    $nsUri = 'http://schemas.android.com/apk/res/android'
    $permissions = @()
    foreach ($module in @('app', 'share-sdk')) {
        [xml]$manifest = Get-Content -LiteralPath (Join-Path $androidRoot "$module/src/main/AndroidManifest.xml") -Raw
        $permissions += @($manifest.SelectNodes('/manifest/uses-permission') | ForEach-Object { $_.GetAttribute('name', $nsUri) })
        if ($module -eq 'app') {
            $service = $manifest.SelectSingleNode('/manifest/application/service')
            if (!$service -or $service.GetAttribute('foregroundServiceType', $nsUri) -ne 'connectedDevice' -or $service.GetAttribute('exported', $nsUri) -ne 'false') { throw 'Foreground service contract mismatch' }
        }
    }
    foreach ($permission in @('INTERNET', 'ACCESS_NETWORK_STATE', 'FOREGROUND_SERVICE', 'FOREGROUND_SERVICE_CONNECTED_DEVICE', 'CHANGE_NETWORK_STATE', 'POST_NOTIFICATIONS')) {
        if ("android.permission.$permission" -notin $permissions) { throw "Missing manifest permission: $permission" }
    }
    foreach ($permission in @('MANAGE_EXTERNAL_STORAGE', 'READ_EXTERNAL_STORAGE', 'WRITE_EXTERNAL_STORAGE', 'ACCESS_LOCAL_NETWORK')) {
        if ("android.permission.$permission" -in $permissions) { throw "Unexpected target-36/storage permission: $permission" }
    }
    Write-Output 'PASS static module, SDK, manifest permission and connectedDevice service contracts'
}

function Test-JunitReport([string]$Directory, [string]$Label) {
    if (!(Test-Path -LiteralPath $Directory -PathType Container)) { throw "Missing test report directory: $Directory" }
    $files = @(Get-ChildItem -LiteralPath $Directory -Recurse -File -Filter 'TEST-*.xml')
    if ($files.Count -eq 0) { throw "Missing XML test reports: $Directory" }
    $tests = 0; $failures = 0; $errors = 0; $skipped = 0
    foreach ($file in $files) {
        [xml]$report = Get-Content -LiteralPath $file.FullName -Raw
        $suites = @($report.SelectNodes('/testsuite | /testsuites/testsuite'))
        if ($suites.Count -eq 0) { throw "Invalid JUnit report: $($file.FullName)" }
        foreach ($suite in $suites) {
            foreach ($attribute in @('tests', 'failures', 'errors', 'skipped')) {
                $value = $suite.GetAttribute($attribute)
                if ($value -notmatch '^\d+$') { throw "Invalid $attribute count: $($file.FullName)" }
            }
            $tests += [int]$suite.tests; $failures += [int]$suite.failures
            $errors += [int]$suite.errors; $skipped += [int]$suite.skipped
        }
    }
    Write-Output "$Label XML: tests=$tests failures=$failures errors=$errors skipped=$skipped files=$($files.Count)"
    if ($tests -eq 0 -or $failures -ne 0 -or $errors -ne 0 -or $skipped -ne 0) { throw "$Label gate failed (empty, failed or skipped tests)" }
}

function Test-Deliverables {
    Require-File (Join-Path $OutputRoot 'app/build/outputs/apk/debug/app-debug.apk')
    $manifestPath = Join-Path $OutputRoot 'app/build/intermediates/merged_manifests/debug/processDebugManifest/AndroidManifest.xml'
    Require-File $manifestPath
    [xml]$merged = Get-Content -LiteralPath $manifestPath -Raw
    $androidNs = 'http://schemas.android.com/apk/res/android'
    if ($merged.manifest.package -ne 'com.unishare.app') { throw 'Wrong merged application ID' }
    $usesSdk = $merged.SelectSingleNode('/manifest/uses-sdk')
    if (!$usesSdk -or $usesSdk.GetAttribute('minSdkVersion', $androidNs) -ne '26' -or $usesSdk.GetAttribute('targetSdkVersion', $androidNs) -ne '36') { throw 'Wrong merged min/target SDK' }
    $mergedPermissions = @($merged.SelectNodes('/manifest/uses-permission') | ForEach-Object { $_.GetAttribute('name', $androidNs) })
    foreach ($permission in @('INTERNET', 'ACCESS_NETWORK_STATE', 'FOREGROUND_SERVICE', 'FOREGROUND_SERVICE_CONNECTED_DEVICE', 'CHANGE_NETWORK_STATE', 'POST_NOTIFICATIONS')) {
        if ("android.permission.$permission" -notin $mergedPermissions) { throw "Missing merged manifest permission: $permission" }
    }
    Write-Output 'PASS existing merged manifest application ID, API26/target36 and permissions'
    Test-JunitReport (Join-Path $OutputRoot 'app/build/test-results/testDebugUnitTest') 'App unit'
    Require-File (Join-Path $OutputRoot 'app/build/reports/tests/testDebugUnitTest/index.html')
    foreach ($module in @('app')) {
        $xmlPath = Join-Path $OutputRoot "$module/build/reports/lint-results-debug.xml"
        Require-File $xmlPath
        Require-File (Join-Path $OutputRoot "$module/build/reports/lint-results-debug.html")
        [xml]$lint = Get-Content -LiteralPath $xmlPath -Raw
        if ($lint.DocumentElement.Name -ne 'issues') { throw "Invalid lint report: $xmlPath" }
        $issues = @($lint.SelectNodes('/issues/issue'))
        $fatal = @($issues | Where-Object { $_.severity -in @('Error', 'Fatal') })
        Write-Output "$module lint XML: errors=$($fatal.Count) warnings=$(@($issues | Where-Object { $_.severity -eq 'Warning' }).Count)"
        if ($fatal.Count -gt 0) { throw "$module lint gate failed: $($fatal.id -join ', ')" }
    }
    Require-File (Join-Path $OutputRoot 'share-sdk/build/outputs/aar/share-sdk-debug.aar')
    if ($DeviceSerial) {
        foreach ($module in @('app', 'share-sdk')) {
            Test-JunitReport (Join-Path $OutputRoot "$module/build/outputs/androidTest-results/connected/debug") "$module connected (existing reports; verify device provenance separately)"
            Require-File (Join-Path $OutputRoot "$module/build/reports/androidTests/connected/debug/index.html")
        }
    } else { Write-Output 'SKIP connected report gate: no -DeviceSerial selected. This does not pass a device/release gate.' }
    Write-Output "PASS existing deliverables at $OutputRoot (presence/results only; freshness and physical acceptance require operator evidence)"
}

function Resolve-Adb {
    if ($AdbPath) { Require-File $AdbPath; return [IO.Path]::GetFullPath($AdbPath) }
    foreach ($sdkRoot in @($env:ANDROID_HOME, $env:ANDROID_SDK_ROOT)) {
        if ($sdkRoot) {
            $candidate = Join-Path $sdkRoot 'platform-tools/adb.exe'
            if (Test-Path -LiteralPath $candidate -PathType Leaf) { return $candidate }
        }
    }
    $properties = Join-Path $androidRoot 'local.properties'
    if (Test-Path -LiteralPath $properties) {
        $line = Get-Content -LiteralPath $properties | Where-Object { $_ -match '^sdk\.dir=' } | Select-Object -First 1
        if ($line) {
            $sdkRoot = $line.Substring(8).Replace('\:', ':').Replace('\\', '\')
            $candidate = Join-Path $sdkRoot 'platform-tools/adb.exe'
            if (Test-Path -LiteralPath $candidate -PathType Leaf) { return $candidate }
        }
    }
    $command = Get-Command adb.exe -ErrorAction SilentlyContinue
    if ($command) { return $command.Source }
    throw 'Selected connected gate requires adb; supply -AdbPath or configure Android SDK'
}

function Confirm-SelectedDevice {
    if (!$DeviceSerial) {
        Write-Output 'SKIP connected execution: no -DeviceSerial selected (even if adb has devices). Select an online serial explicitly; device/release gate remains unverified.'
        return
    }
    if ($DeviceSerial -match '\s') { throw 'DeviceSerial must be one exact adb serial without whitespace' }
    $adb = Resolve-Adb
    $devices = @(& $adb devices -l)
    if ($LASTEXITCODE -ne 0) { throw 'adb devices failed' }
    if (!($devices | Where-Object { $_ -match ('^' + [regex]::Escape($DeviceSerial) + '\s+device(?:\s|$)') })) {
        throw "Selected device is not online/authorized: $DeviceSerial. Use adb devices -l; no connected task was started."
    }
    $api = (& $adb -s $DeviceSerial shell getprop ro.build.version.sdk) -join ''
    if ($LASTEXITCODE -ne 0 -or $api.Trim() -notmatch '^\d+$') { throw 'Could not read selected device API' }
    $model = (& $adb -s $DeviceSerial shell getprop ro.product.model) -join ''
    if ($LASTEXITCODE -ne 0) { throw 'Could not read selected device model' }
    Write-Output "Selected device: $DeviceSerial API=$($api.Trim()) model=$($model.Trim()). Record emulator/physical provenance separately."
}

function Invoke-Gradle([string[]]$Tasks) {
    Write-Output "RUN Gradle: $($Tasks -join ' ')"
    & (Join-Path $androidRoot 'gradlew.bat') -p $androidRoot @Tasks --console=plain
    if ($LASTEXITCODE -ne 0) { throw "Gradle failed ($LASTEXITCODE): $($Tasks -join ' ')" }
}

$previousSerial = $env:ANDROID_SERIAL
try {
    Test-StaticContract
    if (!$VerifyOnly) {
        if ($OutputRoot -ne $androidRoot) { throw '-OutputRoot is supported only with -VerifyOnly; normal runs use actual Gradle output paths' }
        Confirm-SelectedDevice
        if ($DeviceSerial) { $env:ANDROID_SERIAL = $DeviceSerial }
        else { Remove-Item Env:ANDROID_SERIAL -ErrorAction SilentlyContinue }
        $inventory = @(& (Join-Path $androidRoot 'gradlew.bat') -p $androidRoot :app:tasks --all :share-sdk:tasks --all --console=plain)
        if ($LASTEXITCODE -ne 0) { throw 'Gradle task inventory failed' }
        foreach ($task in @('assembleDebug', 'testDebugUnitTest', 'lintDebug', 'connectedDebugAndroidTest')) {
            if (@($inventory | Where-Object { $_ -match ('^' + $task + '(?:\s|$)') }).Count -lt 2) { throw "Missing actual app/share-sdk Gradle task: $task" }
        }
        Write-Output 'PASS actual Gradle task inventory for both modules'
        Invoke-Gradle @(':app:testDebugUnitTest', ':app:lintDebug', ':share-sdk:testDebugUnitTest', ':share-sdk:assembleDebug', ':app:assembleDebug')
        Write-Output 'SDK testDebugUnitTest may be NO-SOURCE: current SDK contracts run on-device via PublicApiTests, not host JUnit.'
        if ($DeviceSerial) {
            # ANDROID_SERIAL is AGP/ddmlib selection. Never use adb -d/-e or all devices.
            Invoke-Gradle @(':app:connectedDebugAndroidTest')
            Invoke-Gradle @(':share-sdk:connectedDebugAndroidTest', '-PpublicTests=ON')
        }
    } else {
        Write-Output 'VerifyOnly: no Gradle, adb, build, installation or test execution; examining existing evidence only.'
    }
    Test-Deliverables
    exit 0
} catch {
    [Console]::Error.WriteLine("FAIL: $($_.Exception.Message)")
    exit 1
} finally {
    if ($null -eq $previousSerial) { Remove-Item Env:ANDROID_SERIAL -ErrorAction SilentlyContinue }
    else { $env:ANDROID_SERIAL = $previousSerial }
}
